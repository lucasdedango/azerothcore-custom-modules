static std::string MakeItemLink(uint32 itemId)
{
    ItemTemplate const* proto = sObjectMgr->GetItemTemplate(itemId);
    if (!proto)
        return "[item:" + std::to_string(itemId) + "]";

    return "|c" + std::string(ItemQualityColor(proto->Quality)) +
        "|Hitem:" + std::to_string(itemId) +
        ":0:0:0:0:0:0:0|h[" + proto->Name1 + "]|h|r";
}

static uint32 RegisterSubstitution(
    Player* player,
    SubstitutionKind kind,
    uint32 originalItemId,
    int32 originalRandomPropertyId,
    uint32 substituteItemId)
{
    if (!player)
        return 0;

    uint32 id = g_NextSubstitutionId.fetch_add(1);
    if (id == 0)
        id = g_NextSubstitutionId.fetch_add(1);

    SubstitutionRecord record;
    record.Id = id;
    record.PlayerGuid = PreferenceKey(player);
    record.Kind = kind;
    record.OriginalItemId = originalItemId;
    record.OriginalRandomPropertyId = originalRandomPropertyId;
    record.SubstituteItemId = substituteItemId;

    {
        std::lock_guard<std::mutex> lock(g_SubstitutionMutex);
        auto& history = g_SubstitutionHistory[record.PlayerGuid];
        history.push_back(record);

        uint32 maxRecords = std::max<uint32>(1, g_Config.MaxUndoRecordsPerCharacter);
        while (history.size() > maxRecords)
            history.pop_front();
    }

    return id;
}

static void NotifyReplacement(
    Player* player,
    uint32 id,
    uint32 originalItemId,
    uint32 substituteItemId)
{
    if (!g_Config.NotifySubstitutions || !player || !player->GetSession())
        return;

    ChatHandler handler(player->GetSession());
    std::string message =
        "|cff00ff96[SmartLoot #" + std::to_string(id) + "]|r " +
        MakeItemLink(originalItemId) + " |cffffffff->|r " +
        MakeItemLink(substituteItemId) +
        " |cffaaaaaa(annuler: .subundo " + std::to_string(id) + ")|r";

    handler.SendSysMessage(message);
}

static void NotifyBonus(
    Player* player,
    uint32 id,
    uint32 originalItemId,
    uint32 bonusItemId)
{
    if (!g_Config.NotifySubstitutions || !player || !player->GetSession())
        return;

    ChatHandler handler(player->GetSession());
    std::string message =
        "|cff00ff96[SmartLoot #" + std::to_string(id) + "]|r " +
        MakeItemLink(originalItemId) +
        " |cffffd100conserve; bonus de substitution:|r " +
        MakeItemLink(bonusItemId) +
        " |cffaaaaaa(annuler le bonus: .subundo " + std::to_string(id) + ")|r";

    handler.SendSysMessage(message);
}

static SubstitutionRecord* FindSubstitutionRecordLocked(uint64 playerGuid, uint32 id)
{
    auto historyItr = g_SubstitutionHistory.find(playerGuid);
    if (historyItr == g_SubstitutionHistory.end())
        return nullptr;

    for (SubstitutionRecord& record : historyItr->second)
        if (record.Id == id)
            return &record;

    return nullptr;
}

static std::string ToLower(std::string value)
{
    std::transform(value.begin(), value.end(), value.begin(),
        [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return value;
}

static std::string Trim(std::string value)
{
    auto notSpace = [](unsigned char c) { return !std::isspace(c); };

    value.erase(value.begin(), std::find_if(value.begin(), value.end(), notSpace));
    value.erase(std::find_if(value.rbegin(), value.rend(), notSpace).base(), value.end());

    return value;
}

static std::string CurrentModeDescription(Player* player)
{
    ArmorPreference pref = GetPreference(player);

    std::string result = "Smart loot mode: ";
    result += PreferenceName(pref);

    if (pref == ArmorPreference::Auto)
    {
        result += " (current armor target: ";

        switch (GetHighestCurrentArmorSubclass(player))
        {
            case ITEM_SUBCLASS_ARMOR_PLATE:   result += "Plate / Plaque"; break;
            case ITEM_SUBCLASS_ARMOR_MAIL:    result += "Mail / Maille"; break;
            case ITEM_SUBCLASS_ARMOR_LEATHER: result += "Leather / Cuir"; break;
            default:                          result += "Cloth / Tissu"; break;
        }

        result += ")";
    }

    return result;
}

class SoloLootRerollMiscScript : public MiscScript
{
public:
    SoloLootRerollMiscScript()
        : MiscScript("SoloLootRerollMiscScript", { MISCHOOK_ON_AFTER_LOOT_TEMPLATE_PROCESS })
    {
    }

    void OnAfterLootTemplateProcess(
        Loot* loot,
        LootTemplate const* lootTemplate,
        LootStore const& store,
        Player* lootOwner,
        bool /*personal*/,
        bool /*noEmptyError*/,
        uint16 lootMode) override
    {
        if (!g_Config.Enable || !loot || !lootOwner)
            return;

        // This module intentionally operates only on normal creature/boss loot.
        if (&store != &LootTemplates_Creature)
            return;

        // One or many real players are supported. The module chooses one
        // eligible real player uniformly at random for THIS loot generation.
        // Players using ".lootignore on" are removed from the candidate set.
        Player* realPlayer = SelectRandomEligibleRealPlayer(lootOwner);
        if (!realPlayer)
            return;

        ArmorPreference pref = GetPreference(realPlayer);
        if (pref == ArmorPreference::Off)
            return;

        uint32 lootId = GetCreatureLootIdForTemplate(lootTemplate);
        if (!lootId)
            return;

        std::shared_ptr<std::vector<Candidate>> pool = GetCandidatePool(lootId);
        if (!pool || pool->empty())
            return;

        // Only process the items that existed when the normal loot generation
        // finished. Bonus items appended by this module are not recursively
        // reconsidered.
        size_t originalItemCount = loot->items.size();

        for (size_t i = 0; i < originalItemCount && i < loot->items.size(); ++i)
        {
            LootItem const& originalLootItem = loot->items[i];

            if (originalLootItem.is_looted ||
                originalLootItem.needs_quest ||
                !originalLootItem.conditions.empty())
                continue;

            ItemTemplate const* originalProto =
                sObjectMgr->GetItemTemplate(originalLootItem.itemid);

            if (!originalProto || originalProto->Quality < g_Config.MinQuality)
                continue;

            GearCategory category = GetCategory(originalProto);

            if (category == GearCategory::Armor && !g_Config.EnableArmor)
                continue;

            if (category == GearCategory::Weapon && !g_Config.EnableWeapons)
                continue;

            if (category == GearCategory::None)
                continue;

            if (IsUsefulForPlayer(realPlayer, originalProto, category))
                continue;

            uint32 originalItemId = originalLootItem.itemid;
            uint32 quality = originalProto->Quality;

            // Green: replace with another usable green from the same reachable
            // creature loot pool. Slot does NOT have to match.
            if (quality == ITEM_QUALITY_UNCOMMON && g_Config.ReplaceUncommon)
            {
                if (Candidate const* replacement = SelectCandidate(
                        *pool,
                        loot,
                        realPlayer,
                        category,
                        ITEM_QUALITY_UNCOMMON,
                        lootMode,
                        originalItemId))
                {
                    int32 originalRandomPropertyId = loot->items[i].randomPropertyId;

                    if (ReplaceLootItem(loot, i, *replacement))
                    {
                        uint32 substitutionId = RegisterSubstitution(
                            realPlayer,
                            SubstitutionKind::Replacement,
                            originalItemId,
                            originalRandomPropertyId,
                            replacement->ItemId);

                        NotifyReplacement(
                            realPlayer,
                            substitutionId,
                            originalItemId,
                            replacement->ItemId);

                        if (g_Config.Debug)
                        {
                            LOG_INFO(
                                "module",
                                "[mod-solo-loot-reroll] {}: SmartLoot #{} replaced green item {} with {} (lootId {})",
                                realPlayer->GetName(), substitutionId, originalItemId, replacement->ItemId, lootId);
                        }
                    }
                }

                continue;
            }

            if (quality < ITEM_QUALITY_RARE)
                continue;

            // Rare+ (blue/epic/legendary...):
            // 1) first try to replace with a usable item of THE SAME QUALITY;
            // 2) if none exists, keep the original item and append the highest
            //    lower-quality compatible item available in the same loot pool.
            if (g_Config.ReplaceRareOrHigher)
            {
                if (Candidate const* replacement = SelectCandidate(
                        *pool,
                        loot,
                        realPlayer,
                        category,
                        quality,
                        lootMode,
                        originalItemId))
                {
                    int32 originalRandomPropertyId = loot->items[i].randomPropertyId;

                    if (ReplaceLootItem(loot, i, *replacement))
                    {
                        uint32 substitutionId = RegisterSubstitution(
                            realPlayer,
                            SubstitutionKind::Replacement,
                            originalItemId,
                            originalRandomPropertyId,
                            replacement->ItemId);

                        NotifyReplacement(
                            realPlayer,
                            substitutionId,
                            originalItemId,
                            replacement->ItemId);

                        if (g_Config.Debug)
                        {
                            LOG_INFO(
                                "module",
                                "[mod-solo-loot-reroll] {}: SmartLoot #{} replaced item {} with same-quality item {} (quality {}, lootId {})",
                                realPlayer->GetName(), substitutionId, originalItemId, replacement->ItemId, quality, lootId);
                        }

                        continue;
                    }
                }
            }

            if (g_Config.LowerQualityFallbackBonus &&
                loot->items.size() < MAX_NR_LOOT_ITEMS)
            {
                if (Candidate const* bonus = SelectBestLowerQualityCandidate(
                        *pool,
                        loot,
                        realPlayer,
                        category,
                        quality,
                        lootMode,
                        originalItemId))
                {
                    ItemTemplate const* bonusProto = sObjectMgr->GetItemTemplate(bonus->ItemId);

                    if (AddBonusItem(loot, *bonus))
                    {
                        uint32 substitutionId = RegisterSubstitution(
                            realPlayer,
                            SubstitutionKind::Bonus,
                            originalItemId,
                            originalLootItem.randomPropertyId,
                            bonus->ItemId);

                        NotifyBonus(
                            realPlayer,
                            substitutionId,
                            originalItemId,
                            bonus->ItemId);

                        if (g_Config.Debug)
                        {
                            LOG_INFO(
                                "module",
                                "[mod-solo-loot-reroll] {}: SmartLoot #{} kept item {} (quality {}) and added lower-quality bonus {} (quality {}, lootId {})",
                                realPlayer->GetName(),
                                substitutionId,
                                originalItemId,
                                quality,
                                bonus->ItemId,
                                bonusProto ? bonusProto->Quality : 0,
                                lootId);
                        }
                    }
                }
            }
        }
    }
};


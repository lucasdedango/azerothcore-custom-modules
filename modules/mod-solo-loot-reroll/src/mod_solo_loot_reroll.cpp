/*
 * mod-solo-loot-reroll
 *
 * Smart creature-loot rerolling for AzerothCore Playerbot:
 * - active with one OR several real online players;
 * - for each creature loot, one non-ignored real player is selected at random;
 * - armor defaults to the highest armor proficiency the player currently has;
 * - weapons are filtered with Player::CanUseItem;
 * - an unusable/wrong armor or weapon first tries to reroll into another usable
 *   item of the SAME quality from the same creature loot pool;
 * - if no same-quality replacement exists, the original item stays and the
 *   highest lower-quality compatible item available can be added as a bonus.
 *
 * No custom SQL tables are created. The module only READS AzerothCore's
 * existing creature/reference loot tables and conditions table.
 */


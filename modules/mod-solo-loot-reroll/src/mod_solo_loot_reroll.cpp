enum class ArmorPreference : uint8
{
    Auto = 0,
    Cloth,
    Leather,
    Mail,
    Plate,
    Off
};

enum class GearCategory : uint8
{
    None = 0,
    Armor,
    Weapon
};

struct ConfigData
{
    bool Enable = true;
    bool EnableArmor = true;
    bool EnableWeapons = true;
    uint32 MinQuality = ITEM_QUALITY_UNCOMMON;

    // Conservative anti-farming defaults:
    // greens may be replaced by another green, rare+ are kept.
    bool ReplaceUncommon = true;
    bool ReplaceRareOrHigher = true;

    // If no usable same-quality replacement exists, keep the original item and
    // add the highest lower-quality compatible item available in the same pool.
    bool LowerQualityFallbackBonus = true;

    // Player feedback / undo history.
    bool NotifySubstitutions = true;
    uint32 MaxUndoRecordsPerCharacter = 100;

    bool Debug = false;
};

struct Candidate
{
    uint32 ItemId = 0;
    float Weight = 1.0f;
    uint16 EffectiveLootMode = LOOT_MODE_DEFAULT;
    uint8 GroupId = 0;
    uint8 MinCount = 1;
    uint8 MaxCount = 1;
};


enum class SubstitutionKind : uint8
{
    Replacement = 0,
    Bonus = 1
};

struct SubstitutionRecord
{
    uint32 Id = 0;
    uint64 PlayerGuid = 0;
    SubstitutionKind Kind = SubstitutionKind::Replacement;

    // Original drop generated by AzerothCore.
    uint32 OriginalItemId = 0;
    int32 OriginalRandomPropertyId = 0;

    // Item inserted by the module.
    uint32 SubstituteItemId = 0;

    bool Undone = false;
};


static ConfigData g_Config;

// Character preferences are intentionally session-only.
// Auto is the default, therefore no persistence/custom SQL table is needed.
static std::unordered_map<uint64, ArmorPreference> g_Preferences;
static std::mutex g_PreferencesMutex;

// Players can opt out of being selected as the smart-loot target.
// Session-only: no custom SQL table is required.
static std::unordered_set<uint64> g_IgnoredLootPlayers;
static std::mutex g_IgnoredLootPlayersMutex;

static std::atomic<uint32> g_NextSubstitutionId{1};
static std::unordered_map<uint64, std::deque<SubstitutionRecord>> g_SubstitutionHistory;
static std::mutex g_SubstitutionMutex;

// Loot caches are built lazily from the existing World DB.
static std::unordered_map<uint32, std::shared_ptr<std::vector<Candidate>>> g_PoolCache;
static std::unordered_map<LootTemplate const*, uint32> g_TemplateToCreatureLootId;
static bool g_TemplateMapBuilt = false;
static std::mutex g_CacheMutex;

static bool IsPlayerBot(Player const* player)
{
    if (!player)
        return false;

    WorldSession const* session = player->GetSession();

    // This is a native flag in the Playerbot fork's WorldSession and is set
    // for PlayerBot sessions. It avoids account-name / character-name guesses.
    return session && session->IsBot();
}

static uint64 PreferenceKey(Player const* player)
{
    return player ? player->GetGUID().GetRawValue() : 0;
}

static bool IsLootIgnored(Player const* player)
{
    if (!player)
        return true;

    std::lock_guard<std::mutex> lock(g_IgnoredLootPlayersMutex);
    return g_IgnoredLootPlayers.count(PreferenceKey(player)) != 0;
}

static void SetLootIgnored(Player const* player, bool ignored)
{
    if (!player)
        return;

    std::lock_guard<std::mutex> lock(g_IgnoredLootPlayersMutex);

    if (ignored)
        g_IgnoredLootPlayers.insert(PreferenceKey(player));
    else
        g_IgnoredLootPlayers.erase(PreferenceKey(player));
}

static void ForgetLootIgnored(Player const* player)
{
    if (!player)
        return;

    std::lock_guard<std::mutex> lock(g_IgnoredLootPlayersMutex);
    g_IgnoredLootPlayers.erase(PreferenceKey(player));
}

static std::vector<Player*> GetEligibleRealPlayers(Player* lootOwner)
{
    std::vector<Player*> players;

    if (!lootOwner)
        return players;

    Group* group = lootOwner->GetGroup();

    if (!group)
    {
        if (!IsPlayerBot(lootOwner) && !IsLootIgnored(lootOwner))
            players.push_back(lootOwner);

        return players;
    }

    for (GroupReference* ref = group->GetFirstMember(); ref; ref = ref->next())
    {
        Player* member = ref->GetSource();

        if (!member || IsPlayerBot(member) || IsLootIgnored(member))
            continue;

        players.push_back(member);
    }

    return players;
}

static Player* SelectRandomEligibleRealPlayer(Player* lootOwner)
{
    std::vector<Player*> players = GetEligibleRealPlayers(lootOwner);

    if (players.empty())
        return nullptr;

    if (players.size() == 1)
        return players.front();

    return players[urand(0, static_cast<uint32>(players.size() - 1))];
}

static ArmorPreference GetPreference(Player const* player)
{
    std::lock_guard<std::mutex> lock(g_PreferencesMutex);
    auto itr = g_Preferences.find(PreferenceKey(player));
    return itr != g_Preferences.end() ? itr->second : ArmorPreference::Auto;
}

static void SetPreference(Player const* player, ArmorPreference pref)
{
    std::lock_guard<std::mutex> lock(g_PreferencesMutex);

    if (pref == ArmorPreference::Auto)
        g_Preferences.erase(PreferenceKey(player));
    else
        g_Preferences[PreferenceKey(player)] = pref;
}

static void ForgetPreference(Player const* player)
{
    std::lock_guard<std::mutex> lock(g_PreferencesMutex);
    g_Preferences.erase(PreferenceKey(player));
}

static char const* PreferenceName(ArmorPreference pref)
{
    switch (pref)
    {
        case ArmorPreference::Auto:    return "Auto";
        case ArmorPreference::Cloth:   return "Cloth / Tissu";
        case ArmorPreference::Leather: return "Leather / Cuir";
        case ArmorPreference::Mail:    return "Mail / Maille";
        case ArmorPreference::Plate:   return "Plate / Plaque";
        case ArmorPreference::Off:     return "Off";
    }

    return "Unknown";
}

static uint32 ArmorSubclassFromPreference(ArmorPreference pref)
{
    switch (pref)
    {
        case ArmorPreference::Cloth:   return ITEM_SUBCLASS_ARMOR_CLOTH;
        case ArmorPreference::Leather: return ITEM_SUBCLASS_ARMOR_LEATHER;
        case ArmorPreference::Mail:    return ITEM_SUBCLASS_ARMOR_MAIL;
        case ArmorPreference::Plate:   return ITEM_SUBCLASS_ARMOR_PLATE;
        default:                       return ITEM_SUBCLASS_ARMOR_CLOTH;
    }
}

static uint32 GetHighestCurrentArmorSubclass(Player const* player)
{
    if (!player)
        return ITEM_SUBCLASS_ARMOR_CLOTH;

    // This uses the player's CURRENT proficiencies, rather than a class-name
    // approximation. It therefore naturally handles the WotLK level-40
    // transitions (Leather->Mail, Mail->Plate) once the skill is learned.
    if (player->HasSkill(SKILL_PLATE_MAIL))
        return ITEM_SUBCLASS_ARMOR_PLATE;

    if (player->HasSkill(SKILL_MAIL))
        return ITEM_SUBCLASS_ARMOR_MAIL;

    if (player->HasSkill(SKILL_LEATHER))
        return ITEM_SUBCLASS_ARMOR_LEATHER;

    return ITEM_SUBCLASS_ARMOR_CLOTH;
}

static uint32 GetDesiredArmorSubclass(Player const* player)
{
    ArmorPreference pref = GetPreference(player);

    if (pref == ArmorPreference::Auto)
        return GetHighestCurrentArmorSubclass(player);

    return ArmorSubclassFromPreference(pref);
}

static bool IsBodyArmor(ItemTemplate const* proto)
{
    if (!proto || proto->Class != ITEM_CLASS_ARMOR)
        return false;

    if (proto->SubClass < ITEM_SUBCLASS_ARMOR_CLOTH ||
        proto->SubClass > ITEM_SUBCLASS_ARMOR_PLATE)
        return false;

    switch (proto->InventoryType)
    {
        case INVTYPE_HEAD:
        case INVTYPE_SHOULDERS:
        case INVTYPE_CHEST:
        case INVTYPE_WAIST:
        case INVTYPE_LEGS:
        case INVTYPE_FEET:
        case INVTYPE_WRISTS:
        case INVTYPE_HANDS:
        case INVTYPE_ROBE:
            return true;
        default:
            return false;
    }
}

static bool IsWeapon(ItemTemplate const* proto)
{
    if (!proto || proto->Class != ITEM_CLASS_WEAPON)
        return false;

    // Never turn combat loot into a fishing pole.
    return proto->SubClass != ITEM_SUBCLASS_WEAPON_FISHING_POLE;
}

static GearCategory GetCategory(ItemTemplate const* proto)
{
    if (IsBodyArmor(proto))
        return GearCategory::Armor;

    if (IsWeapon(proto))
        return GearCategory::Weapon;

    return GearCategory::None;
}

static bool IsUsefulForPlayer(Player* player, ItemTemplate const* proto, GearCategory category)
{
    if (!player || !proto)
        return false;

    if (player->CanUseItem(proto) != EQUIP_ERR_OK)
        return false;

    if (category == GearCategory::Armor)
        return proto->SubClass == GetDesiredArmorSubclass(player);

    if (category == GearCategory::Weapon)
        return true;

    return false;
}

static std::unordered_set<int32> LoadConditionedSourceEntries(uint32 sourceType, uint32 sourceGroup)
{
    std::unordered_set<int32> result;

    QueryResult query = WorldDatabase.Query(
        "SELECT DISTINCT SourceEntry FROM conditions "
        "WHERE SourceTypeOrReferenceId = {} AND SourceGroup = {}",
        sourceType, sourceGroup);

    if (!query)
        return result;

    do
    {
        Field* fields = query->Fetch();
        result.insert(fields[0].Get<int32>());
    }
    while (query->NextRow());

    return result;
}

static void LoadReferenceRows(
    uint32 referenceEntry,
    uint16 inheritedLootMode,
    float inheritedWeight,
    std::unordered_set<uint32>& referenceStack,
    std::vector<Candidate>& out)
{
    if (!referenceEntry || referenceStack.count(referenceEntry))
        return;

    referenceStack.insert(referenceEntry);

    std::unordered_set<int32> conditioned =
        LoadConditionedSourceEntries(CONDITION_SOURCE_TYPE_REFERENCE_LOOT_TEMPLATE, referenceEntry);

    QueryResult query = WorldDatabase.Query(
        "SELECT Item, Reference, Chance, QuestRequired, LootMode, GroupId, MinCount, MaxCount "
        "FROM reference_loot_template WHERE Entry = {}",
        referenceEntry);

    if (query)
    {
        do
        {
            Field* fields = query->Fetch();

            uint32 itemId = fields[0].Get<uint32>();
            int32 reference = fields[1].Get<int32>();
            float chance = fields[2].Get<float>();
            bool needsQuest = fields[3].Get<bool>();
            uint16 rowLootMode = fields[4].Get<uint16>();
            uint8 groupId = fields[5].Get<uint8>();
            uint8 minCount = fields[6].Get<uint8>();
            uint8 maxCount = fields[7].Get<uint8>();

            if (!rowLootMode)
                rowLootMode = LOOT_MODE_DEFAULT;

            uint16 effectiveMode = inheritedLootMode & rowLootMode;
            if (!effectiveMode)
                continue;

            // If this row has a DB condition, skip it rather than bypassing
            // AzerothCore's condition system when creating the replacement.
            if (conditioned.count(static_cast<int32>(itemId)))
                continue;

            if (reference > 0)
            {
                float refChanceFactor = chance > 0.0f ? (chance / 100.0f) : 1.0f;
                float repeatFactor = maxCount > 0 ? static_cast<float>(maxCount) : 1.0f;

                LoadReferenceRows(
                    static_cast<uint32>(reference),
                    effectiveMode,
                    inheritedWeight * refChanceFactor * repeatFactor,
                    referenceStack,
                    out);

                continue;
            }

            if (!itemId || needsQuest)
                continue;

            Candidate candidate;
            candidate.ItemId = itemId;
            candidate.Weight = inheritedWeight * (chance > 0.0f ? chance : 1.0f);
            candidate.EffectiveLootMode = effectiveMode;
            candidate.GroupId = groupId;
            candidate.MinCount = minCount ? minCount : 1;
            candidate.MaxCount = maxCount >= candidate.MinCount ? maxCount : candidate.MinCount;

            out.push_back(candidate);
        }
        while (query->NextRow());
    }

    referenceStack.erase(referenceEntry);
}

static std::shared_ptr<std::vector<Candidate>> LoadCreaturePool(uint32 lootId)
{
    auto result = std::make_shared<std::vector<Candidate>>();

    std::unordered_set<int32> conditioned =
        LoadConditionedSourceEntries(CONDITION_SOURCE_TYPE_CREATURE_LOOT_TEMPLATE, lootId);

    QueryResult query = WorldDatabase.Query(
        "SELECT Item, Reference, Chance, QuestRequired, LootMode, GroupId, MinCount, MaxCount "
        "FROM creature_loot_template WHERE Entry = {}",
        lootId);

    if (!query)
        return result;

    std::unordered_set<uint32> referenceStack;

    do
    {
        Field* fields = query->Fetch();

        uint32 itemId = fields[0].Get<uint32>();
        int32 reference = fields[1].Get<int32>();
        float chance = fields[2].Get<float>();
        bool needsQuest = fields[3].Get<bool>();
        uint16 rowLootMode = fields[4].Get<uint16>();
        uint8 groupId = fields[5].Get<uint8>();
        uint8 minCount = fields[6].Get<uint8>();
        uint8 maxCount = fields[7].Get<uint8>();

        if (!rowLootMode)
            rowLootMode = LOOT_MODE_DEFAULT;

        if (conditioned.count(static_cast<int32>(itemId)))
            continue;

        if (reference > 0)
        {
            float refChanceFactor = chance > 0.0f ? (chance / 100.0f) : 1.0f;
            float repeatFactor = maxCount > 0 ? static_cast<float>(maxCount) : 1.0f;

            LoadReferenceRows(
                static_cast<uint32>(reference),
                rowLootMode,
                refChanceFactor * repeatFactor,
                referenceStack,
                *result);

            continue;
        }

        if (!itemId || needsQuest)
            continue;

        Candidate candidate;
        candidate.ItemId = itemId;
        candidate.Weight = chance > 0.0f ? chance : 1.0f;
        candidate.EffectiveLootMode = rowLootMode;
        candidate.GroupId = groupId;
        candidate.MinCount = minCount ? minCount : 1;
        candidate.MaxCount = maxCount >= candidate.MinCount ? maxCount : candidate.MinCount;

        result->push_back(candidate);
    }
    while (query->NextRow());

    return result;
}

static void BuildTemplateMapLocked()
{
    g_TemplateToCreatureLootId.clear();

    QueryResult query = WorldDatabase.Query("SELECT DISTINCT Entry FROM creature_loot_template");

    if (query)
    {
        do
        {
            Field* fields = query->Fetch();
            uint32 entry = fields[0].Get<uint32>();

            if (LootTemplate const* lootTemplate = LootTemplates_Creature.GetLootFor(entry))
                g_TemplateToCreatureLootId[lootTemplate] = entry;
        }
        while (query->NextRow());
    }

    g_TemplateMapBuilt = true;
}

static uint32 GetCreatureLootIdForTemplate(LootTemplate const* lootTemplate)
{
    if (!lootTemplate)
        return 0;

    std::lock_guard<std::mutex> lock(g_CacheMutex);

    if (!g_TemplateMapBuilt)
        BuildTemplateMapLocked();

    auto itr = g_TemplateToCreatureLootId.find(lootTemplate);
    if (itr != g_TemplateToCreatureLootId.end())
        return itr->second;

    // Loot tables can be reloaded by a GM. Rebuild once if the pointer changed.
    BuildTemplateMapLocked();

    itr = g_TemplateToCreatureLootId.find(lootTemplate);
    return itr != g_TemplateToCreatureLootId.end() ? itr->second : 0;
}

static std::shared_ptr<std::vector<Candidate>> GetCandidatePool(uint32 lootId)
{
    std::lock_guard<std::mutex> lock(g_CacheMutex);

    auto itr = g_PoolCache.find(lootId);
    if (itr != g_PoolCache.end())
        return itr->second;

    std::shared_ptr<std::vector<Candidate>> pool = LoadCreaturePool(lootId);
    g_PoolCache[lootId] = pool;
    return pool;
}

static bool LootAlreadyContains(Loot const* loot, uint32 itemId)
{
    if (!loot)
        return false;

    for (LootItem const& item : loot->items)
        if (!item.is_looted && item.itemid == itemId)
            return true;

    return false;
}

static Candidate const* SelectCandidate(
    std::vector<Candidate> const& pool,
    Loot const* loot,
    Player* player,
    GearCategory category,
    uint32 quality,
    uint16 lootMode,
    uint32 excludedItemId)
{
    std::vector<Candidate const*> eligible;
    float totalWeight = 0.0f;

    for (Candidate const& candidate : pool)
    {
        if (candidate.ItemId == excludedItemId)
            continue;

        if (!(candidate.EffectiveLootMode & lootMode))
            continue;

        if (LootAlreadyContains(loot, candidate.ItemId))
            continue;

        ItemTemplate const* proto = sObjectMgr->GetItemTemplate(candidate.ItemId);
        if (!proto || proto->Quality != quality)
            continue;

        if (GetCategory(proto) != category)
            continue;

        if (!IsUsefulForPlayer(player, proto, category))
            continue;

        float weight = candidate.Weight > 0.0f ? candidate.Weight : 1.0f;
        eligible.push_back(&candidate);
        totalWeight += weight;
    }

    if (eligible.empty())
        return nullptr;

    if (eligible.size() == 1 || totalWeight <= 0.0f)
        return eligible.front();

    float roll = frand(0.0f, totalWeight);

    for (Candidate const* candidate : eligible)
    {
        roll -= candidate->Weight > 0.0f ? candidate->Weight : 1.0f;
        if (roll <= 0.0f)
            return candidate;
    }

    return eligible.back();
}

static Candidate const* SelectBestLowerQualityCandidate(
    std::vector<Candidate> const& pool,
    Loot const* loot,
    Player* player,
    GearCategory category,
    uint32 originalQuality,
    uint16 lootMode,
    uint32 excludedItemId)
{
    if (originalQuality <= g_Config.MinQuality)
        return nullptr;

    // Prefer the closest lower rarity:
    // Epic -> Rare -> Uncommon, Rare -> Uncommon, etc.
    for (int32 quality = static_cast<int32>(originalQuality) - 1;
         quality >= static_cast<int32>(g_Config.MinQuality);
         --quality)
    {
        if (Candidate const* candidate = SelectCandidate(
                pool,
                loot,
                player,
                category,
                static_cast<uint32>(quality),
                lootMode,
                excludedItemId))
        {
            return candidate;
        }
    }

    return nullptr;
}

static LootStoreItem MakeLootStoreItem(Candidate const& candidate)
{
    // Equippable loot should be a single item. Preserve the source GroupId and
    // loot mode, but force a count of 1 for a reroll/bonus to avoid accidental
    // multi-count equipment from unusual custom tables.
    return LootStoreItem(
        candidate.ItemId,
        0,
        100.0f,
        false,
        candidate.EffectiveLootMode ? candidate.EffectiveLootMode : LOOT_MODE_DEFAULT,
        candidate.GroupId,
        1,
        1);
}

static bool ReplaceLootItem(Loot* loot, size_t index, Candidate const& candidate)
{
    if (!loot || index >= loot->items.size())
        return false;

    size_t before = loot->items.size();
    uint32 originalIndex = loot->items[index].itemIndex;

    LootStoreItem generatedFrom = MakeLootStoreItem(candidate);
    loot->AddItem(generatedFrom);

    if (loot->items.size() != before + 1)
        return false;

    LootItem replacement = std::move(loot->items.back());
    loot->items.pop_back();

    replacement.itemIndex = originalIndex;
    loot->items[index] = std::move(replacement);
    return true;
}

static bool AddBonusItem(Loot* loot, Candidate const& candidate)
{
    if (!loot || loot->items.size() >= MAX_NR_LOOT_ITEMS)
        return false;

    size_t before = loot->items.size();

    LootStoreItem generatedFrom = MakeLootStoreItem(candidate);
    loot->AddItem(generatedFrom);

    return loot->items.size() == before + 1;
}



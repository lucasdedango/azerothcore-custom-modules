class SoloLootRerollCommandScript : public CommandScript
{
public:
    SoloLootRerollCommandScript() : CommandScript("SoloLootRerollCommandScript") {}

    ChatCommandTable GetCommands() const override
    {
        static ChatCommandTable commandTable =
        {
            { "loottypeset", HandleLootTypeSet, SEC_PLAYER, Console::No },
            { "loottype",    HandleLootTypeInfo, SEC_PLAYER, Console::No },
            { "lootignore",  HandleLootIgnore, SEC_PLAYER, Console::No },
            { "subundo",     HandleSubUndo, SEC_PLAYER, Console::No }
        };

        return commandTable;
    }

    static bool HandleLootIgnore(ChatHandler* handler, char const* args)
    {
        Player* player = handler->GetPlayer();
        if (!player)
            return false;

        std::string value = ToLower(Trim(args ? args : ""));

        if (value.empty() || value == "status")
        {
            handler->PSendSysMessage(
                "SmartLoot selection: {}.",
                IsLootIgnored(player)
                    ? "IGNORED - vous ne serez pas choisi comme cible de substitution"
                    : "ELIGIBLE - vous pouvez etre choisi comme cible de substitution");

            handler->SendSysMessage(
                "Usage: .lootignore on|off  (alias logique: on = m'ignorer, off = me reprendre)");
            return true;
        }

        if (value == "on" || value == "1" || value == "yes" ||
            value == "oui" || value == "ignore" || value == "ignored")
        {
            SetLootIgnored(player, true);
            handler->SendSysMessage(
                "SmartLoot: vous etes maintenant ignore pour les substitutions. Les autres joueurs eligibles seront favorises.");
            return true;
        }

        if (value == "off" || value == "0" || value == "no" ||
            value == "non" || value == "enable" || value == "eligible")
        {
            SetLootIgnored(player, false);
            handler->SendSysMessage(
                "SmartLoot: vous etes de nouveau eligible pour les substitutions.");
            return true;
        }

        handler->SendSysMessage("Usage: .lootignore on|off|status");
        return false;
    }

    static bool HandleSubUndo(ChatHandler* handler, char const* args)
    {
        Player* player = handler->GetPlayer();
        if (!player)
            return false;

        std::string value = Trim(args ? args : "");
        if (value.empty())
        {
            handler->SendSysMessage("Usage: .subundo <id>");
            return false;
        }

        uint32 id = 0;
        try
        {
            size_t parsed = 0;
            unsigned long parsedId = std::stoul(value, &parsed, 10);
            if (parsed != value.size() || parsedId == 0 || parsedId > UINT32_MAX)
                throw std::invalid_argument("bad id");

            id = static_cast<uint32>(parsedId);
        }
        catch (...)
        {
            handler->SendSysMessage("ID invalide. Usage: .subundo <id>");
            return false;
        }

        SubstitutionRecord snapshot;

        {
            std::lock_guard<std::mutex> lock(g_SubstitutionMutex);
            SubstitutionRecord* record = FindSubstitutionRecordLocked(PreferenceKey(player), id);

            if (!record)
            {
                handler->PSendSysMessage(
                    "SmartLoot #{} introuvable (mauvais personnage, historique expire ou redemarrage serveur).",
                    id);
                return false;
            }

            if (record->Undone)
            {
                handler->PSendSysMessage("SmartLoot #{} a deja ete annule.", id);
                return false;
            }

            snapshot = *record;
        }

        // The substituted/bonus item must really be owned by THIS character.
        // inBankAlso=false intentionally does not accept an item sitting in the bank.
        if (!player->HasItemCount(snapshot.SubstituteItemId, 1, false))
        {
            std::string message =
                "Impossible d'annuler SmartLoot #" + std::to_string(id) +
                ": " + MakeItemLink(snapshot.SubstituteItemId) +
                " n'est pas dans votre inventaire/equipement.";
            handler->SendSysMessage(message);
            return false;
        }

        if (snapshot.Kind == SubstitutionKind::Bonus)
        {
            player->DestroyItemCount(snapshot.SubstituteItemId, 1, true);

            {
                std::lock_guard<std::mutex> lock(g_SubstitutionMutex);
                if (SubstitutionRecord* record = FindSubstitutionRecordLocked(PreferenceKey(player), id))
                    record->Undone = true;
            }

            std::string message =
                "|cff00ff96[SmartLoot #" + std::to_string(id) +
                "]|r bonus annule: " + MakeItemLink(snapshot.SubstituteItemId) +
                " retire. Le drop original " + MakeItemLink(snapshot.OriginalItemId) +
                " reste inchange.";
            handler->SendSysMessage(message);
            return true;
        }

        // Replacement undo is transactional from the player's point of view:
        // first ensure the original item FITS, then remove the substitute.
        ItemPosCountVec dest;
        InventoryResult canStore =
            player->CanStoreNewItem(NULL_BAG, NULL_SLOT, dest, snapshot.OriginalItemId, 1);

        if (canStore != EQUIP_ERR_OK)
        {
            std::string message =
                "Impossible d'annuler SmartLoot #" + std::to_string(id) +
                ": pas de place pour restaurer " + MakeItemLink(snapshot.OriginalItemId) +
                ". Aucun objet n'a ete retire.";
            handler->SendSysMessage(message);
            return false;
        }

        player->DestroyItemCount(snapshot.SubstituteItemId, 1, true);

        Item* restored = player->StoreNewItem(
            dest,
            snapshot.OriginalItemId,
            true,
            snapshot.OriginalRandomPropertyId);

        if (!restored)
        {
            // Extremely defensive rollback: if the core unexpectedly refuses the
            // original after CanStoreNewItem succeeded, restore the substitute.
            player->StoreNewItemInBestSlots(snapshot.SubstituteItemId, 1);

            handler->PSendSysMessage(
                "Echec inattendu de SmartLoot #{}: substitution restauree, aucune perte volontaire.",
                id);
            return false;
        }

        {
            std::lock_guard<std::mutex> lock(g_SubstitutionMutex);
            if (SubstitutionRecord* record = FindSubstitutionRecordLocked(PreferenceKey(player), id))
                record->Undone = true;
        }

        std::string message =
            "|cff00ff96[SmartLoot #" + std::to_string(id) + "]|r annule: " +
            MakeItemLink(snapshot.SubstituteItemId) + " |cffffffff->|r " +
            MakeItemLink(snapshot.OriginalItemId) + ".";
        handler->SendSysMessage(message);

        return true;
    }

    static bool HandleLootTypeInfo(ChatHandler* handler, char const* /*args*/)
    {
        Player* player = handler->GetPlayer();
        if (!player)
            return false;

        std::string message = CurrentModeDescription(player);
        handler->SendSysMessage(message.c_str());

        Group* group = player->GetGroup();
        uint32 realPlayers = 0;
        uint32 eligibleRealPlayers = 0;
        uint32 ignoredRealPlayers = 0;
        uint32 bots = 0;

        auto countMember = [&](Player* member)
        {
            if (!member)
                return;

            if (IsPlayerBot(member))
            {
                ++bots;
                return;
            }

            ++realPlayers;

            if (IsLootIgnored(member))
                ++ignoredRealPlayers;
            else
                ++eligibleRealPlayers;
        };

        if (!group)
            countMember(player);
        else
            for (GroupReference* ref = group->GetFirstMember(); ref; ref = ref->next())
                countMember(ref->GetSource());

        handler->SendSysMessage(
            eligibleRealPlayers > 0
                ? "SmartLoot group condition: active. One eligible real player is chosen randomly for each generated creature loot."
                : "SmartLoot group condition: inactive. No eligible real player is available.");

        std::string counts =
            "Online group members: " + std::to_string(realPlayers) +
            " real player(s) (" + std::to_string(eligibleRealPlayers) +
            " eligible, " + std::to_string(ignoredRealPlayers) +
            " ignored), " + std::to_string(bots) + " PlayerBot(s).";
        handler->SendSysMessage(counts.c_str());

        handler->PSendSysMessage(
            "Your SmartLoot selection state: {}.",
            IsLootIgnored(player) ? "IGNORED" : "ELIGIBLE");

        handler->SendSysMessage(
            "Weapons: automatic; an unusable weapon may be rerolled/compensated with a weapon the randomly selected player can use.");

        return true;
    }

    static bool HandleLootTypeSet(ChatHandler* handler, char const* args)
    {
        Player* player = handler->GetPlayer();
        if (!player)
            return false;

        std::string value = ToLower(Trim(args ? args : ""));

        if (value.empty() || value == "status")
            return HandleLootTypeInfo(handler, "");

        ArmorPreference pref;

        if (value == "auto" || value == "automatic" || value == "automatique" || value == "reset")
            pref = ArmorPreference::Auto;
        else if (value == "off" || value == "none" || value == "disable" || value == "desactive")
            pref = ArmorPreference::Off;
        else if (value == "cloth" || value == "tissu")
            pref = ArmorPreference::Cloth;
        else if (value == "leather" || value == "cuir")
            pref = ArmorPreference::Leather;
        else if (value == "mail" || value == "maille")
            pref = ArmorPreference::Mail;
        else if (value == "plate" || value == "plaque")
            pref = ArmorPreference::Plate;
        else
        {
            handler->SendSysMessage(
                "Usage: .loottypeset auto|off|tissu|cloth|cuir|leather|maille|mail|plaque|plate");
            return false;
        }

        SetPreference(player, pref);

        std::string message = "Smart loot preference set to: ";
        message += PreferenceName(pref);
        handler->SendSysMessage(message.c_str());

        if (pref == ArmorPreference::Auto)
        {
            std::string autoMessage = CurrentModeDescription(player);
            handler->SendSysMessage(autoMessage.c_str());
        }
        else if (pref == ArmorPreference::Off)
        {
            handler->SendSysMessage(
                "Smart reroll is disabled for this character until relog/restart or '.loottypeset auto'.");
        }

        return true;
    }
};

